update public.recipe_catalog c
set recipes = (
    select jsonb_agg(case when p.makes is null then e else e || jsonb_build_object('makes', p.makes) end order by t.n)
    from jsonb_array_elements(c.recipes) with ordinality as t(e, n) left join p on p.title = t.e->>'title'
  ),
  updated_at = now()
where c.source = 'claude'
  and exists (select 1 from jsonb_array_elements(c.recipes) e join p on p.title = e->>'title');

-- Pour vérifier : le nombre de recettes qui ont leur compte (161 attendues au moins une fois)
